/**
 * Object storage for files that are too large to travel inside a function
 * request or to live in a MongoDB document: source uploads and generated
 * files of the direct-upload pipeline.
 *
 * The rest of the server talks to this interface only. Two drivers exist:
 *
 *  - `vercel-blob`: a private Vercel Blob store. The browser uploads straight
 *    to the store with a short-lived client token, and downloads are streamed
 *    through an authenticated route. Nothing in the store is public.
 *  - `local`: a directory on disk, for development and tests on a long-lived
 *    Node server. It is refused on serverless hosts, whose disks do not persist.
 *
 * Object paths are generated by the server (see `objectPaths.ts`). A path
 * received from a browser is never used to address storage.
 */
import { capacity } from "../config/env.js";

export type StoredObject = {
  path: string;
  bytes: number;
  contentType: string;
};

/** What the browser needs to upload one file directly to storage. */
export type UploadGrant =
  | {
      transport: "vercel-blob";
      /** The only pathname the token is valid for. */
      pathname: string;
      /** Short-lived token bound to the pathname, size and content type. It cannot read or delete. */
      clientToken: string;
      access: "private";
      /** Whether the browser should split the upload into parts. */
      multipart: boolean;
    }
  | {
      transport: "local";
      /** Same-origin URL that accepts the file body with PUT. Carries a signature and an expiry. */
      uploadUrl: string;
    };

export type UploadAuthorization = {
  uploadId: string;
  path: string;
  contentType: string;
  /** Exact size the browser declared. Storage rejects more. */
  maxBytes: number;
  /** Epoch milliseconds after which the grant is useless. */
  validUntil: number;
  /** Days after which storage deletes the object on its own. */
  ttlDays: number;
};

export type ObjectReader = {
  stream: ReadableStream<Uint8Array>;
  bytes: number;
  contentType: string;
};

export interface ObjectStorage {
  readonly driver: "vercel-blob" | "local";
  authorizeUpload(input: UploadAuthorization): Promise<UploadGrant>;
  /** Metadata of the object, or null when it does not exist. */
  head(path: string): Promise<StoredObject | null>;
  /** Opens the object for reading, or returns null when it does not exist. */
  read(path: string): Promise<ObjectReader | null>;
  write(path: string, data: Buffer, options: { contentType: string; ttlDays: number }): Promise<StoredObject>;
  /** Deletes objects. A path that does not exist is not an error. */
  remove(paths: string[]): Promise<void>;
}

export type ObjectStorageErrorCode =
  /** The store rejected the credentials, does not exist, or has the wrong access mode. */
  | "storage_misconfigured"
  /** A temporary failure: network, rate limit, or the service being unavailable. */
  | "storage_unavailable"
  /** The object is larger than the operation allows. */
  | "object_too_large";

/** A storage failure in terms the pipeline can act on. Carries no provider message. */
export class ObjectStorageError extends Error {
  readonly code: ObjectStorageErrorCode;
  readonly retryable: boolean;
  constructor(code: ObjectStorageErrorCode, options?: { cause?: unknown }) {
    super(code, options);
    this.name = "ObjectStorageError";
    this.code = code;
    this.retryable = code === "storage_unavailable";
  }
}

/** Storage deletes on whole days. Rounds a retention period up, within the range the provider accepts. */
export function ttlDaysFor(ms: number): number {
  return Math.min(730, Math.max(1, Math.ceil(ms / 86_400_000)));
}

export type StorageDriverName = "vercel-blob" | "local";

/** Why direct uploads are, or are not, possible on this deployment. Contains no secrets. */
export type StorageStatus =
  | { configured: true; driver: StorageDriverName }
  | { configured: false; reason: "not_configured" | "disabled" | "unsupported_host" | "local_dir_missing" };

const onServerless = (): boolean =>
  Boolean(process.env.VERCEL || process.env.NETLIFY || process.env.AWS_LAMBDA_FUNCTION_NAME || process.env.LAMBDA_TASK_ROOT);

/**
 * Which driver the environment selects. Read at call time, so a test can
 * change the environment between cases.
 *
 * `OW_STORAGE_DRIVER` may be `vercel-blob`, `local` or `none`. When unset, a
 * Vercel Blob store is used if its read-write token is present and the server
 * runs on Vercel or on a long-lived Node server. Other serverless hosts buffer
 * function responses, so large downloads could not be streamed from them.
 */
export function storageStatus(): StorageStatus {
  const requested = (process.env.OW_STORAGE_DRIVER ?? "").trim().toLowerCase();
  if (requested === "none") return { configured: false, reason: "disabled" };
  if (requested === "local") {
    if (onServerless()) return { configured: false, reason: "unsupported_host" };
    return process.env.OW_LOCAL_STORAGE_DIR ? { configured: true, driver: "local" } : { configured: false, reason: "local_dir_missing" };
  }
  if (!process.env.BLOB_READ_WRITE_TOKEN) return { configured: false, reason: "not_configured" };
  if (requested !== "vercel-blob" && onServerless() && !process.env.VERCEL) return { configured: false, reason: "unsupported_host" };
  return { configured: true, driver: "vercel-blob" };
}

let cached: { key: string; storage: ObjectStorage } | null = null;
let override: ObjectStorage | null | undefined;

/** The configured storage, or null when direct uploads are not available. */
export async function getObjectStorage(): Promise<ObjectStorage | null> {
  if (override !== undefined) return override;
  const status = storageStatus();
  if (!status.configured) return null;
  const key = `${status.driver}:${process.env.OW_LOCAL_STORAGE_DIR ?? ""}:${(process.env.BLOB_READ_WRITE_TOKEN ?? "").length}`;
  if (cached?.key === key) return cached.storage;
  const storage =
    status.driver === "local"
      ? (await import("./localStorage.js")).createLocalStorage(String(process.env.OW_LOCAL_STORAGE_DIR))
      : (await import("./vercelBlobStorage.js")).createVercelBlobStorage(String(process.env.BLOB_READ_WRITE_TOKEN));
  cached = { key, storage };
  return storage;
}

/** Test hook: use this storage, or `null` for none. `undefined` restores the environment's choice. */
export function setObjectStorageForTests(storage: ObjectStorage | null | undefined): void {
  override = storage;
  cached = null;
}

/** Reads a whole object into memory, refusing anything above `maxBytes`. */
export async function readAll(reader: ObjectReader, maxBytes: number): Promise<Buffer> {
  if (reader.bytes > maxBytes) {
    await reader.stream.cancel().catch(() => undefined);
    throw new ObjectStorageError("object_too_large");
  }
  const chunks: Uint8Array[] = [];
  let total = 0;
  const source = reader.stream.getReader();
  for (;;) {
    const { done, value } = await source.read();
    if (done) break;
    total += value.byteLength;
    if (total > maxBytes) {
      await source.cancel().catch(() => undefined);
      throw new ObjectStorageError("object_too_large");
    }
    chunks.push(value);
  }
  return Buffer.concat(chunks, total);
}

/** The first bytes of an object, enough to recognise its file signature. */
export async function readHead(reader: ObjectReader, length: number): Promise<Buffer> {
  const chunks: Uint8Array[] = [];
  let total = 0;
  const source = reader.stream.getReader();
  while (total < length) {
    const { done, value } = await source.read();
    if (done) break;
    chunks.push(value);
    total += value.byteLength;
  }
  await source.cancel().catch(() => undefined);
  return Buffer.concat(chunks, total).subarray(0, length);
}

/** Days storage keeps a source upload and a generated file on its own, as a backstop behind the cleanup routine. */
export const storageTtlDays = {
  // One extra day each: storage counts whole days, and the cleanup routine is the primary mechanism.
  source: (): number => ttlDaysFor(capacity.sourceTtlMs + capacity.uploadPhaseTtlMs) + 1,
  artifact: (): number => ttlDaysFor(capacity.artifactTtlMs) + 1,
};
