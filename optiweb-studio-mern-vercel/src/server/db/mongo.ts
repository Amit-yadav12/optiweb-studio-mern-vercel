/**
 * MongoDB connection management.
 *
 * One connection promise is cached on `globalThis`, so warm invocations of the
 * same serverless instance reuse the pool instead of reconnecting.
 *
 * The connection string is read from the environment at call time and is never
 * logged, returned or attached to an error. Failures leave this module only as
 * a `StorageUnavailableError` carrying a category from a fixed list; see
 * `storageDiagnostics.ts`.
 */
import mongoose from "mongoose";
import {
  StorageUnavailableError,
  classifyStorageError,
  describeStorageFailure,
  logStorageFailure,
  type StorageFailureCategory,
} from "./storageDiagnostics.js";

type Cache = { connection: typeof mongoose | null; promise: Promise<typeof mongoose> | null };
const globalCache = globalThis as typeof globalThis & { __optiwebMongo?: Cache };
const cache: Cache = (globalCache.__optiwebMongo ??= { connection: null, promise: null });

/**
 * The configured connection string, or `undefined` when none is set.
 *
 * Surrounding whitespace and one pair of wrapping quotes are removed. Both are
 * easy to introduce when a value is copied from a `.env` file into a hosting
 * dashboard, and either one makes an otherwise correct string unparseable.
 */
function mongoUri(): string | undefined {
  const raw = process.env.MONGODB_URI ?? process.env.MONGO_URL;
  if (typeof raw !== "string") return undefined;
  let value = raw.trim();
  if (value.length >= 2 && (value.startsWith('"') || value.startsWith("'")) && value.endsWith(value[0])) {
    value = value.slice(1, -1).trim();
  }
  return value || undefined;
}

/** Whether a connection string is present. Says nothing about whether it works. */
export function isMongoConfigured(): boolean {
  return mongoUri() !== undefined;
}

function serverSelectionTimeoutMs(): number {
  const parsed = Number(process.env.OW_MONGO_TIMEOUT_MS ?? 5000);
  return Number.isFinite(parsed) && parsed > 0 ? Math.min(parsed, 30_000) : 5000;
}

/**
 * Returns the shared connection, opening it if needed.
 *
 * Throws `StorageUnavailableError` with the failure category. It does not log:
 * the storage operation that needed the connection logs once, with its own
 * name and the request ID.
 */
export async function connectMongo(): Promise<typeof mongoose> {
  const uri = mongoUri();
  if (!uri) throw new StorageUnavailableError("not_configured");
  if (cache.connection?.connection.readyState === 1) return cache.connection;
  if (!cache.promise) {
    cache.promise = mongoose.connect(uri, {
      maxPoolSize: Number(process.env.OW_MONGO_POOL_MAX ?? 3),
      serverSelectionTimeoutMS: serverSelectionTimeoutMs(),
      autoIndex: true,
    });
  }
  const attempt = cache.promise;
  try {
    cache.connection = await attempt;
    return cache.connection;
  } catch (error) {
    // Forget the failed attempt so the next request tries again. The guard
    // keeps a slower caller from discarding a newer attempt.
    if (cache.promise === attempt) {
      cache.promise = null;
      cache.connection = null;
    }
    throw new StorageUnavailableError(classifyStorageError(error, "connect"), { cause: error });
  }
}

/** Readiness of the database for this application. Contains no connection details. */
export type MongoReadiness = {
  /** A connection string is set. */
  configured: boolean;
  /** The server accepted the connection and answered a ping. */
  connected: boolean;
  /** Connected, and the server accepted both a read and a write command on the job collection. */
  ready: boolean;
  /** Time taken by the whole check, when it succeeded. */
  latencyMs: number | null;
  /** Present when `ready` is false. */
  category?: StorageFailureCategory;
  /** Fixed, client-safe wording for the category. */
  error?: string;
  hint?: string;
};

/** Collection that holds job records. The job model uses it, and the readiness check probes it. */
export const JOBS_COLLECTION = "optiweb_jobs";

/**
 * `_id` used by the readiness check's write probe. Job IDs are always UUIDs
 * generated by the server, so no job record can have this ID.
 */
const READINESS_PROBE_ID = "__optiweb_readiness_probe__";

/**
 * Actual readiness, checked with the configured credentials. Never throws.
 *
 *  1. connect and ping: the server is reachable and accepts the credentials;
 *  2. read one document ID from the job collection: the user may read it;
 *  3. send a delete that matches nothing: a writable server accepts a write
 *     command from this user. Nothing is deleted or created, including the
 *     collection itself, so the check never changes data.
 *
 * Step 3 catches a read-only database user and a replica set without a
 * primary. It cannot predict a write that is refused for its content or size,
 * such as a full storage quota; the operation that attempts such a write
 * reports it.
 */
export async function probeMongo(): Promise<MongoReadiness> {
  const started = Date.now();
  const configured = isMongoConfigured();
  let stage: "connect" | "read" | "write" = "connect";
  let connected = false;
  try {
    const client = await connectMongo();
    const db = client.connection.db;
    if (!db) throw new StorageUnavailableError("connection_failed");
    await db.admin().ping();
    connected = true;
    const jobs = db.collection<{ _id: string }>(JOBS_COLLECTION);
    stage = "read";
    await jobs.findOne({}, { projection: { _id: 1 } });
    stage = "write";
    await jobs.deleteOne({ _id: READINESS_PROBE_ID });
    return { configured, connected: true, ready: true, latencyMs: Date.now() - started };
  } catch (error) {
    const category = classifyStorageError(error, stage);
    logStorageFailure({ category, operation: "health.probe", stage, error: unwrap(error), durationMs: Date.now() - started });
    const failure = describeStorageFailure(category);
    return { configured, connected, ready: false, latencyMs: null, category, error: failure.message, hint: failure.hint };
  }
}

/** The driver error behind a `StorageUnavailableError`, for log metadata only. */
export function unwrap(error: unknown): unknown {
  return error instanceof StorageUnavailableError && error.cause !== undefined ? error.cause : error;
}

/** Test hook: closes the connection and forgets it, so a different URI can be used in the same process. */
export async function disconnectMongo(): Promise<void> {
  cache.promise = null;
  cache.connection = null;
  await mongoose.disconnect().catch(() => undefined);
}
